"""Regenerate the browser's empty AutoCAD 2007 document (requires ezdxf 1.4.3+).

Keep the complete tables, layout dictionaries and ownership graph: permissive
readers accept partial documents which AutoCAD's DXFIN can reject.
"""
import io
import json
import re
from pathlib import Path
import ezdxf

doc = ezdxf.new('R2007')
doc.units = 4
doc.header['$MEASUREMENT'] = 1
doc.header['$LUNITS'] = 2
doc.header['$LUPREC'] = 2
doc.styles.get('Standard').dxf.font = 'Arial.ttf'
for name, color in [('PANELES', 4), ('NUMERIAI', 7), ('MATMENYS', 3), ('GEOMETRIJA', 6), ('PASTABOS', 7)]:
    doc.layers.new(name, dxfattribs={'color': color})
# Fixed metadata keeps regeneration reproducible.
for key in ('$TDCREATE', '$TDUPDATE', '$TDUCREATE', '$TDUUPDATE'):
    doc.header[key] = 2451544.5
for key in ('$FINGERPRINTGUID', '$VERSIONGUID'):
    doc.header[key] = '{00000000-0000-0000-0000-000000000000}'
stream = io.StringIO()
doc.write(stream)
raw = stream.getvalue()
# Normalize pair formatting and line endings for the browser writer.
lines = raw.splitlines()
pairs = [(int(lines[i].strip()), lines[i+1]) for i in range(0, len(lines), 2)]
for i, (code, value) in enumerate(pairs):
    if code == 9 and value == '$HANDSEED':
        pairs[i+1] = (5, '__HANDSEED__')
    if code == 1 and value.startswith('1.4.'):
        pairs[i] = (code, 'LED Studija DXF template')
raw = ''.join(f'{code}\r\n{value}\r\n' for code, value in pairs)
marker = '0\r\nSECTION\r\n2\r\nENTITIES\r\n'
prefix, suffix = raw.split(marker)
assert suffix.startswith('0\r\nENDSEC\r\n')
assert max(int(value, 16) for code, value in pairs if code in (5, 105) and value != '__HANDSEED__') < 0x1000
out = '// Generated by scripts/generate-dxf-template.py; complete empty AC1021 document.\n'
out += f'export const modelSpaceHandle = {json.dumps(doc.modelspace().block_record_handle)};\n'
out += f'export const dxfPrefix = {json.dumps(prefix + marker)};\n'
out += f'export const dxfSuffix = {json.dumps(suffix)};\n'
Path('src/lib/dxf-template.ts').write_text(out)
